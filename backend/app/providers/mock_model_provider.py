"""Deterministic development model provider for local testing and simulation."""

from __future__ import annotations

import math
from datetime import datetime, timedelta
from typing import Any

from app.providers.model_provider import BaseModelProvider, PredictionOutput


class DevelopmentModelProvider(BaseModelProvider):
    """Deterministic development model provider.
    
    CRITICAL: Demo predictions are always explicitly marked as demo results.
    Never presents mock outputs as verified production predictions.
    """

    PROVIDER_NAME = "development_mock_v1"

    MODEL_REGISTRY_MAP = {
        "commercial": {
            "model_name": "commercial-demand-forecast",
            "version": "dev-mock-1.1.3",
            "target_name": "hourly_demand_kwh",
            "target_unit": "kWh per hourly record",
            "base_kw": 350.0,
        },
        "residential": {
            "model_name": "residential-month-end-pipeline",
            "version": "dev-mock-1.2.0",
            "target_name": "target_remaining_kwh",
            "target_unit": "kWh",
            "tariff_inr_per_kwh": 10.0,
            "base_kw": 140.0,
        },
        "government": {
            "model_name": "government-regional-demand",
            "version": "dev-mock-1.0.5",
            "target_name": "total_demand_kwh",
            "target_unit": "kWh per hourly record",
            "base_kw": 48000.0,
        },
    }

    def predict(
        self,
        model_name: str,
        entity_id: str,
        features: dict[str, Any],
        actual_kwh_so_far: float | None = None,
        context: str = "future_forecast",
    ) -> PredictionOutput:
        model_key = model_name.lower()
        if "residential" in model_key or model_key == "residential":
            cfg = self.MODEL_REGISTRY_MAP["residential"]
            # Deterministic simulation of remaining kWh
            elapsed_days = float(features.get("elapsed_days", 19))
            remaining_days = max(1.0, 30.0 - elapsed_days)
            daily_avg = float(features.get("daily_avg_kwh", 15.0))
            predicted_remaining = round(daily_avg * remaining_days * 0.98, 2)

            total_month_end = (
                round(actual_kwh_so_far + predicted_remaining, 2)
                if actual_kwh_so_far is not None
                else None
            )
            tariff = cfg["tariff_inr_per_kwh"]
            bill_inr = (
                round(total_month_end * tariff, 2)
                if total_month_end is not None
                else None
            )

            caveats = [
                "DEMO PREDICTION: Generated by DevelopmentMockModelProvider.",
                "Not connected to MLflow or verified production models.",
            ]
            if context == "retrospective_gold_replay":
                caveats.append("Retrospective replay simulation.")

            return PredictionOutput(
                entity_id=entity_id,
                prediction=predicted_remaining,
                target_name=cfg["target_name"],
                target_unit=cfg["target_unit"],
                model_name=cfg["model_name"],
                model_version=cfg["version"],
                is_demo=True,
                provider=self.PROVIDER_NAME,
                evaluation_status="development_mock_only",
                prediction_status="valid",
                actual_kwh_so_far=actual_kwh_so_far,
                estimated_month_end_kwh=total_month_end,
                estimated_month_end_bill_inr=bill_inr,
                tariff_inr_per_kwh=tariff,
                caveats=caveats,
            )

        elif "government" in model_key or model_key == "government":
            cfg = self.MODEL_REGISTRY_MAP["government"]
            base = cfg["base_kw"]
            predicted = round(base * 1.02, 2)
            return PredictionOutput(
                entity_id=entity_id,
                prediction=predicted,
                target_name=cfg["target_name"],
                target_unit=cfg["target_unit"],
                model_name=cfg["model_name"],
                model_version=cfg["version"],
                is_demo=True,
                provider=self.PROVIDER_NAME,
                evaluation_status="development_mock_only",
                prediction_status="valid",
                caveats=[
                    "DEMO PREDICTION: Generated by DevelopmentMockModelProvider.",
                    "Regional simulation mode.",
                ],
            )
        else:
            # Commercial default
            cfg = self.MODEL_REGISTRY_MAP["commercial"]
            sqm = float(features.get("sqm", 14250))
            scale = sqm / 14250.0
            predicted = round(351.2 * scale, 2)
            return PredictionOutput(
                entity_id=entity_id,
                prediction=predicted,
                target_name=cfg["target_name"],
                target_unit=cfg["target_unit"],
                model_name=cfg["model_name"],
                model_version=cfg["version"],
                is_demo=True,
                provider=self.PROVIDER_NAME,
                evaluation_status="development_mock_only",
                prediction_status="valid",
                caveats=[
                    "DEMO PREDICTION: Generated by DevelopmentMockModelProvider.",
                    "Commercial facility simulation mode.",
                ],
            )

    def predict_horizon(
        self,
        sector: str,
        entity_id: str,
        horizon_count: int = 24,
    ) -> list[dict[str, Any]]:
        points: list[dict[str, Any]] = []
        now = datetime(2026, 10, 19, 0, 0)

        # Scale based on sector
        if sector == "commercial":
            # 10-hour or 24-hour hourly forecast
            for h in range(10):
                t = now + timedelta(hours=14 + h)
                time_str = t.strftime("%H:00")
                is_history = h < 3
                base = 340.0 + math.sin(h * 0.6) * 45.0
                pred = 348.0 + math.sin(h * 0.6) * 48.0
                points.append({
                    "timestamp": t.isoformat() + "Z",
                    "formattedTime": time_str,
                    "actualDemand": round(base, 1) if is_history else None,
                    "forecastDemand": round(pred, 1) if not is_history or h == 2 else None,
                    "upperConfidence": round(pred * 1.08, 1) if not is_history else None,
                    "lowerConfidence": round(pred * 0.92, 1) if not is_history else None,
                    "peakThreshold": 400.0,
                    "unit": "kWh",
                })
        elif sector == "residential":
            # 10-day forecast horizon
            start_date = datetime(2026, 10, 10)
            for d in range(10):
                dt = start_date + timedelta(days=d)
                day_str = dt.strftime("%d %b")
                is_history = d < 5
                base = 14.5 + math.sin(d * 0.8) * 3.5
                pred = 15.0 + math.sin(d * 0.8) * 3.8
                points.append({
                    "timestamp": dt.isoformat() + "Z",
                    "formattedTime": day_str,
                    "actualDemand": round(base, 1) if is_history else None,
                    "forecastDemand": round(pred, 1) if not is_history or d == 4 else None,
                    "upperConfidence": round(pred * 1.10, 1) if not is_history else None,
                    "lowerConfidence": round(pred * 0.90, 1) if not is_history else None,
                    "peakThreshold": 22.0,
                    "unit": "kWh",
                })
        else:
            # Regional Government Grid
            for h in range(12):
                t = now + timedelta(hours=h * 2)
                time_str = t.strftime("%H:00")
                is_history = h < 6
                base = 420.0 + math.sin(h * 0.5) * 60.0
                pred = 435.0 + math.sin(h * 0.5) * 65.0
                points.append({
                    "timestamp": t.isoformat() + "Z",
                    "formattedTime": time_str,
                    "actualDemand": round(base, 1) if is_history else None,
                    "forecastDemand": round(pred, 1) if not is_history or h == 5 else None,
                    "actualDemandMw": round(base, 1) if is_history else None,
                    "forecastDemandMw": round(pred, 1) if not is_history or h == 5 else None,
                    "upperConfidence": round(pred * 1.06, 1) if not is_history else None,
                    "lowerConfidence": round(pred * 0.94, 1) if not is_history else None,
                    "peakThreshold": 490.0,
                    "peakThresholdMw": 490.0,
                    "unit": "MW",
                })

        return points

    def get_model_status(self) -> dict[str, Any]:
        return {
            "provider": self.PROVIDER_NAME,
            "status": "ready",
            "is_demo": True,
            "models_loaded": list(self.MODEL_REGISTRY_MAP.keys()),
            "description": "Deterministic local development mock provider. Not connected to MLflow.",
        }
